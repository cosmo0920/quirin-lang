"""W48-OPENSSL-CONTRACT-PLUGIN: how the OpenSSL pin was determined.

Reads (1) each prepared Fluent Bit build's CMake cache for the OpenSSL that
`find_package(OpenSSL)` found, (2) the distribution package that owns that
header directory, and (3) compares the distribution's public headers with
the prepared upstream release's, file by file. Writes one JSON record.

usage: python3 -I pin_evidence.py OUT.json PREPARED_TREE CMAKECACHE...
"""
import hashlib
import json
import os
import subprocess
import sys


def digest(path):
    with open(path, 'rb') as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def main():
    out, tree, caches = sys.argv[1], sys.argv[2], sys.argv[3:]
    found = {}
    for cache in caches:
        with open(cache, errors='replace') as handle:
            for line in handle:
                if line.startswith(('FIND_PACKAGE_MESSAGE_DETAILS_OpenSSL', 'OPENSSL_INCLUDE_DIR',
                                    'OPENSSL_CRYPTO_LIBRARY', 'OPENSSL_SSL_LIBRARY')):
                    key, value = line.rstrip('\n').split('=', 1)
                    found.setdefault(os.path.basename(os.path.dirname(os.path.dirname(cache))) + '/' +
                                     os.path.basename(os.path.dirname(cache)), {})[key] = value
    package = subprocess.run(['dpkg-query', '-W', '-f', '${Package} ${Version}\n', 'libssl-dev', 'libssl3t64'],
                             capture_output=True, text=True).stdout.strip().split('\n')
    owner = subprocess.run(['dpkg', '-S', '/usr/include/openssl/opensslv.h'], capture_output=True,
                           text=True).stdout.strip()
    upstream = os.path.join(tree, 'include/openssl')
    system = '/usr/include/openssl'
    arch = '/usr/include/x86_64-linux-gnu/openssl'
    identical, different, only_upstream, only_system = [], [], [], []
    names = sorted(set(n for n in os.listdir(upstream) if n.endswith('.h')) |
                   set(n for n in os.listdir(system) if n.endswith('.h')))
    for name in names:
        u = os.path.join(upstream, name)
        s = os.path.join(system, name)
        if not os.path.exists(s) and os.path.exists(os.path.join(arch, name)):
            s = os.path.join(arch, name)
        if not os.path.exists(u):
            only_system.append(name)
        elif not os.path.exists(s):
            only_upstream.append(name)
        elif digest(u) == digest(s):
            identical.append(name)
        else:
            different.append(name)
    substantive = {}
    for name in different:
        u = os.path.join(upstream, name)
        s = os.path.join(system, name)
        if not os.path.exists(s):
            s = os.path.join(arch, name)
        result = subprocess.run(['diff', u, s], capture_output=True, text=True).stdout
        lines = [line for line in result.split('\n')
                 if line.startswith(('<', '>')) and 'Generated by' not in line]
        if lines:
            substantive[name] = lines
    # The bindings' prototypes as the distribution's headers declare them
    # (what Fluent Bit compiles against), against the contract set's.
    contracts_path = os.path.join(os.path.dirname(__file__), '../../../../crates/quirin-audit-plugin-openssl/contracts/openssl-3.5.5.json')
    with open(contracts_path) as handle:
        contracts = json.load(handle)
    headers = sorted({b['header'] for b in contracts['bindings']})
    source = ''.join('#include <%s>\n' % h for h in headers)
    dump = subprocess.run(['/usr/lib/llvm-21/bin/clang', '-x', 'c', '-fsyntax-only', '-Xclang', '-ast-dump=json', '-'],
                          input=source.encode(), capture_output=True)
    declared = {}
    for node in json.loads(dump.stdout).get('inner', []):
        if node.get('kind') == 'FunctionDecl':
            declared.setdefault(node['name'], set()).add(node['type']['qualType'])
    prototypes = {'agree': 0, 'disagree': {}}
    for binding in contracts['bindings']:
        spelled = declared.get(binding['function'], set())
        if spelled == {binding['prototype']}:
            prototypes['agree'] += 1
        else:
            prototypes['disagree'][binding['function']] = sorted(spelled)
    record = {
        'schema': 'w48-openssl-pin-evidence/1',
        'distribution_prototypes_vs_contracts': prototypes,
        'substantive_header_differences': substantive,
        'fluent_bit_cmake': found,
        'distribution_packages': package,
        'header_owner': owner,
        'release_headers_vs_distribution': {
            'identical': len(identical),
            'different': different,
            'only_in_release': only_upstream,
            'only_in_distribution': only_system,
        },
    }
    with open(out, 'w') as handle:
        json.dump(record, handle, indent=2)
        handle.write('\n')
    print(json.dumps(record['release_headers_vs_distribution'], indent=1))


main()
