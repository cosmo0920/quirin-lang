#!/usr/bin/env python3
"""Write the class (a) leaves — the provisional-Unsafe evidence base — as a table.

Usage: class_a_table.py CLASSIFICATION.json OUT.md

One row per class (a) leaf: function, exit, acquisition, the witness's refused
steps (each tagged E for a refused store/return of the site, C for a refused
call handed the site, R for any other refusal on the path) and the reading.
Class (a) is provisional-Unsafe evidence under the stated premises, never an
upstream defect claim.
"""

import collections
import json
import pathlib
import sys


def main() -> int:
    classification = json.loads(pathlib.Path(sys.argv[1]).read_text())["classification"]
    rows = [entry for entry in classification if entry["class"] == "a"]
    by_function = collections.OrderedDict()
    for entry in rows:
        by_function.setdefault((entry["unit"], entry["function"]), []).append(entry)
    lines = [
        "# Class (a): the provisional-Unsafe leak evidence base after W44-LEAK-PIN-AUDIT",
        "",
        f"{len(rows)} leaves in {len(by_function)} functions, generated by `scripts/class_a_table.py`",
        "from [classification.json](classification.json). Each leaf's witness path is reachable under the",
        "stated premises and reading confirms the resource unreleased on it. These are provisional",
        "`Unsafe` candidates of the resource projection, **not** upstream defect claims; the",
        "test-failure-path leaves are reachable only when a unit test fails.",
        "",
        "## By function",
        "",
        "| Unit | Function | Leaves | Mechanism | Reading |",
        "|---|---|---:|---|---|",
    ]
    for (unit, function), entries in by_function.items():
        mechanisms = sorted({entry["mechanism"] for entry in entries})
        reason = entries[0]["reason"].replace("|", "\\|")
        lines.append(f"| {unit} | `{function}` | {len(entries)} | {', '.join(mechanisms)} | {reason} |")
    lines += [
        "",
        "## Every leaf",
        "",
        "| # | Function | Exit | Acquired | Refused steps on the witness (line: tag) |",
        "|---:|---|---|---|---|",
    ]
    for index, entry in enumerate(rows, 1):
        steps = []
        for step in entry["witness"]:
            if not step["refused"]:
                continue
            tag = "E" if step["refused_escape"] else "C" if step["refused_call"] else "R"
            steps.append(f"{step['origin'] or step['line']}: {tag}")
        lines.append(
            f"| {index} | `{entry['function']}` | {entry['exit']} | {entry['acquired']} | "
            f"{'; '.join(steps) if steps else 'none'} |"
        )
    pathlib.Path(sys.argv[2]).write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} leaves in {len(by_function)} functions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
