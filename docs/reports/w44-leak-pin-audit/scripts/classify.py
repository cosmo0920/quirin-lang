#!/usr/bin/env python3
"""Classify every baseline leak leaf from its witness and the card's reading.

Usage: classify.py JOINED.json READING.json OUT.json OUT.md

JOINED.json is `join_witnesses.py`'s output over the baseline diagnostics and
the BEFORE census. READING.json is the card's source reading: per function (and
optionally per leaf `FUNCTION@ORIGIN@ACQUIRED`), the class, mechanism and
reason for every leaf the witness alone does not decide.

Two class (b) mechanisms are decided before any reading:

* `cast-return`: the exit is `return (T *) PLACE;` over the leaked site
  (READING.json names these leaves; the witness shows the exit binding);
* `refused-escape`: no witness path avoids a refused statement whose value side
  hands the site on (a refused store or return of it).

Every other leaf has a clean witness and is classified by the reading, which
must cover it; a leaf it does not cover is `d` (unclassifiable) and the script
exits 1. Whether the settled exit state still reports the leaf is recorded, not
decided on: `report_leaks` runs on intermediate iterates, and a leaf the union
join of a later iterate no longer supports can still be a true path witness.
"""

import collections
import json
import pathlib
import re
import sys


def acquired(description):
    match = re.search(r"acquired at (\S+)$", description)
    return match.group(1) if match else "?"


def main() -> int:
    joined = json.loads(pathlib.Path(sys.argv[1]).read_text())["joined"]
    reading = json.loads(pathlib.Path(sys.argv[2]).read_text())
    functions = reading["functions"]
    leaves = reading.get("leaves", {})
    out = []
    missing = []
    for leaf in joined:
        witness = leaf["witness"]
        key = f"{leaf['function']}@{leaf['origin']}@{acquired(leaf['description'])}"
        note = leaves.get(key) or functions.get(leaf["function"])
        if note and note.get("mechanism") == "cast-return":
            klass, mechanism, reason = "b", "cast-return", note["reason"]
        elif witness["clean_path"] is None:
            klass, mechanism = "b", "refused-escape"
            escapes = sorted(
                {
                    f"{step['origin'] or step['line']}: {step['instruction']}"
                    for step in witness["path"] or []
                    if step["refused_read"]
                }
            )
            reason = "every witness path passes a refused store or return of the site"
            if escapes:
                reason += " (" + "; ".join(escapes[:3]) + ")"
        elif note:
            klass, mechanism, reason = note["class"], note["mechanism"], note["reason"]
        else:
            klass, mechanism, reason = "d", "unread", "no reading recorded"
            missing.append(key)
        path = witness["clean_path"] or witness["path"] or []
        out.append(
            {
                "library": leaf["library"],
                "unit": leaf["unit"],
                "function": leaf["function"],
                "line": leaf["line"],
                "exit": leaf["origin"],
                "acquired": acquired(leaf["description"]),
                "class": klass,
                "mechanism": mechanism,
                "reason": reason,
                "settled": witness["settled"],
                "clean_path": witness["clean_path"] is not None,
                "strict_path": witness.get("strict_path") is not None,
                "witness": [
                    {
                        "line": step["line"],
                        "origin": step.get("origin"),
                        "instruction": step["instruction"],
                        "refused": step["refused"],
                        "refused_escape": step["refused_read"],
                        "refused_call": step.get("refused_call", False),
                        "undecided_test": step.get("edge_unknown", False),
                    }
                    for step in path
                ],
            }
        )
    counts = collections.Counter(entry["class"] for entry in out)
    mechanisms = collections.Counter((entry["class"], entry["mechanism"]) for entry in out)
    document = {
        "leaves": len(out),
        "classes": dict(sorted(counts.items())),
        "mechanisms": {f"{k}:{m}": n for (k, m), n in sorted(mechanisms.items())},
        "unread": missing,
        "classification": out,
    }
    pathlib.Path(sys.argv[3]).write_text(json.dumps(document, indent=1) + "\n")
    lines = [
        "# Per-leaf classification of the 271 baseline leak leaves",
        "",
        "Generated by `scripts/classify.py` from `classification.json`; the witness",
        "column is the analyzer's own path (clean when one exists), abbreviated to its",
        "refused steps. Class (a) leaves are provisional-Unsafe evidence, never",
        "upstream defect claims.",
        "",
        "| # | Class | Mechanism | Function | Exit | Acquired | Reason |",
        "|---:|---|---|---|---|---|---|",
    ]
    for index, entry in enumerate(out, 1):
        reason = entry["reason"].replace("|", "\\|")
        lines.append(
            f"| {index} | {entry['class']} | {entry['mechanism']} | `{entry['function']}` | "
            f"{entry['exit']} | {entry['acquired']} | {reason} |"
        )
    lines.append("")
    lines.append("Totals: " + ", ".join(f"({k}) {v}" for k, v in sorted(counts.items())))
    pathlib.Path(sys.argv[4]).write_text("\n".join(lines) + "\n")
    print(json.dumps({k: document[k] for k in ("leaves", "classes", "mechanisms", "unread")}, indent=1))
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
