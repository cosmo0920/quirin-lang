#!/usr/bin/env python3
"""Derive the libc/POSIX function-name list the placement test reads.

Usage: libc_names.py PREPROCESSED_DIR OUT.txt

Scans every line-marked preprocessed unit in PREPROCESSED_DIR (the same private
capture `libc_inventory.py` reads) and collects every identifier that is
**declared or defined at file scope, followed by `(`, inside a header owned by
the `libc6-dev` or `linux-libc-dev` Debian package** (glibc and the Linux UAPI
headers), as `dpkg -S` reports ownership. The output is one name per line,
sorted, after a comment header naming its provenance. It is the set of C
library and POSIX functions visible to the pinned corpus on the audited host;
it is not a claim about any other libc.

Identifiers that are C keywords or attribute spellings the scanner can meet
before a parenthesis (`__attribute__`, `__asm__`, `sizeof`, ...) are dropped.
"""

import pathlib
import re
import subprocess
import sys

MARKER = re.compile(r'^# (\d+) "((?:[^"\\]|\\.)*)"((?: \d)*)\s*$')
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
LIBC_PACKAGES = {"libc6-dev", "linux-libc-dev"}
NOT_NAMES = {
    "__attribute__", "__attribute", "__asm__", "__asm", "asm", "sizeof", "_Alignof",
    "__typeof__", "typeof", "__extension__", "_Static_assert", "__declspec",
    "__nonnull", "__THROW", "_Generic", "__inline", "__restrict", "return", "if",
    "while", "for", "switch", "do", "__builtin_va_list", "__builtin_offsetof",
    "__alignof__", "__typeof", "_Noreturn", "__wur",
}
TYPE_WORDS = {"int", "char", "void", "long", "short", "double", "float", "signed", "unsigned", "_Bool"}


def main() -> int:
    directory, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    per_file = {}
    for unit in sorted(directory.glob("*.i")):
        current, system, depth = None, False, 0
        for line in unit.read_text(errors="replace").split("\n"):
            marker = MARKER.match(line)
            if marker:
                current, system = marker.group(2), " 3" in marker.group(3)
                continue
            position = 0
            while position < len(line):
                char = line[position]
                if char in "\"'":
                    quote = char
                    position += 1
                    while position < len(line) and line[position] != quote:
                        position += 2 if line[position] == "\\" else 1
                    position += 1
                    continue
                if char == "{":
                    depth += 1
                elif char == "}":
                    depth = max(0, depth - 1)
                elif char.isalpha() or char == "_":
                    match = IDENT.match(line, position)
                    word, position = match.group(0), match.end()
                    if system and depth == 0 and line[position:].lstrip().startswith("("):
                        previous = line[: match.start()].rstrip()
                        # A declarator name follows a type word, `*` or `)`, or
                        # opens a line after its return type; an attribute
                        # argument follows `(` or `,`.
                        if not previous or previous[-1] not in "(,":
                            per_file.setdefault(current, set()).add(word)
                    continue
                position += 1
    owners = {}
    files = sorted(f for f in per_file if f and f.startswith("/"))
    for start in range(0, len(files), 200):
        run = subprocess.run(["dpkg", "-S", *files[start : start + 200]], capture_output=True, text=True)
        for row in run.stdout.splitlines():
            package, _, path = row.partition(": ")
            for owned in path.split(", "):
                owners[owned.strip()] = package.split(":")[0]
    names = set()
    for file, words in per_file.items():
        if owners.get(file) in LIBC_PACKAGES:
            names |= {w for w in words if w not in NOT_NAMES and w not in TYPE_WORDS and not w.startswith("__builtin")}
    header = [
        "# libc/POSIX function names visible to the pinned Cycle 19 corpus.",
        "# Generated by docs/reports/w43-libc-contracts/scripts/libc_names.py from the",
        "# line-marked preprocessing of all 185 pinned units: every identifier followed",
        "# by `(` at file scope in a header owned by libc6-dev or linux-libc-dev",
        "# (glibc and Linux UAPI headers, audited host). Read by",
        "# scripts/tests/test_contract_corpus.py: no contract module outside",
        "# providers/quirin-provider-libc may declare one of these names.",
    ]
    out.write_text("\n".join(header + sorted(names)) + "\n")
    print(len(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
