//! Reference execution and C11 emission for `source.http.v1`
//! (card `HTTP-QUIRIN-V1`).
//!
//! # The first true composition through `c_program::merge`
//!
//! Card `C-EMIT-MAIN-UNIFY` built the fragment/entry architecture and named the
//! follow-on `C-EMIT-COMPOSED-VIA-MERGE`, noting that converting the *existing*
//! composed route to [`c_program::merge`] would move pinned bytes. This route is
//! **new** — no pinned bytes exist for it — so it uses the mechanism as designed
//! and is the first consumer to do so:
//!
//! * [`preamble`] contributes this route's own fragments: a banner and the
//!   file-scope arrays holding each transferred message's wire bytes;
//! * `crate::std_socket_c_emit::preamble` contributes the transport's;
//! * [`c_program::merge`] concatenates, **deduplicates** (both routes ask for
//!   `qcore_io.prelude`; the program gets one) and orders by declared section,
//!   which is what puts the socket compatibility header above every include even
//!   though this route contributed no include of its own;
//! * `crate::std_socket_c_emit::entry_parts` supplies the one entry's prologue
//!   and body.
//!
//! There is exactly one [`c_program::assemble`] call and it takes exactly one
//! entry, so a composed program cannot have two `main`s by construction.
//!
//! # Why this route's observation is compared byte for byte (constraint 15c)
//!
//! For the same structural reason `source.socket.v1` gives, and it is inherited
//! rather than restated: **a `source.http.v1` program has one thread of control
//! and creates none.** It spawns no worker, registers no callback and runs no
//! reactor; the only statements that write bytes to a stream are
//! `source.std-io.v1`'s own `print` and `log`, executed in the entry's body in
//! program order. Every record's emitter is therefore `Emitter::Parent`, no
//! worker is ever live, each record is alone in its window and so is a barrier,
//! and the declared `qcore.obs-reordering.v1` relation is strict — of which byte
//! equality is the degenerate case (`strict_iff_byte_equality`).
//!
//! **HTTP traffic writes no record at all.** A request on a loopback stream is
//! not an observation: it reaches no stream the observation is read from. A
//! program that wants to say what happened writes a `print` line saying so, and
//! that line is what is compared.

use std::fmt::Write as _;

use crate::c_program::{self, Fragment, Section};
use crate::std_http::{HttpCertificate, HttpMessageRecord, HttpProgram, lower_transport};
use crate::std_socket_c_emit::{self, SocketEmissionRefusal, SocketObservation};

/// The banner an emitted `source.http.v1` program opens with.
const BANNER: &str = "/* Generated by QCore `source.http.v1` (card HTTP-QUIRIN-V1).\n   \
     Every message below is a byte sequence the checker constructed and the\n   \
     compiler checked against RFC 9112: the version, the framing CRLFs, the\n   \
     required Host field and the Content-Length/body-length equality. */\n";

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum HttpEmissionRefusal {
    /// The certificate is not this program's.
    CertificateDisagrees,
    /// The transport backend refused, carrying its own value rather than a
    /// re-worded copy.
    Transport(SocketEmissionRefusal),
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HttpCEmission {
    pub source: String,
}

/// A `const unsigned char` initialiser list.
fn byte_array(bytes: &[u8]) -> String {
    bytes
        .iter()
        .map(|byte| format!("{byte}u"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The message's wire bytes as a C comment a reader can check by eye, with the
/// framing made visible.
fn annotate(record: &HttpMessageRecord) -> String {
    let mut text = String::new();
    let _ = writeln!(
        text,
        "/* {} `{}`: {} head byte(s) in {} field line(s){}. */",
        record.kind,
        record.binding,
        record.head.len(),
        record.field_count,
        match &record.content {
            Some(content) => format!(", {} content byte(s)", content.len()),
            None => ", no content".to_owned(),
        }
    );
    text
}

/// The file-scope text `source.http.v1` contributes to a program it is part of.
///
/// One fragment per **transferred** message, under the message's own symbol, so
/// the bytes one end sends and the bytes the other end verifies are one object
/// in the emitted translation unit rather than two arrays a reader must compare.
/// A declared message no statement transfers contributes nothing: it was checked
/// exactly as hard, and an unused file-scope array would not survive `-Werror`.
#[must_use]
pub fn preamble(certificate: &HttpCertificate) -> Vec<Fragment> {
    let mut fragments = vec![Fragment::new(Section::Banner, "http.banner", BANNER)];
    for record in certificate
        .messages
        .iter()
        .filter(|record| record.transferred)
    {
        let bytes = record.wire();
        let mut text = annotate(record);
        let _ = writeln!(
            text,
            "static const unsigned char {}[] = {{ {} }};",
            record.symbol,
            byte_array(&bytes)
        );
        fragments.push(Fragment::new(
            Section::FileScope,
            format!("http.message.{}", record.binding),
            text,
        ));
    }
    fragments
}

/// The reference observation, derived from the checked program and its
/// certificate.
///
/// It is the **transport's** observation: the HTTP vocabulary produces no line,
/// so there is nothing for this route to add and nothing it may change.
///
/// # Errors
///
/// [`HttpEmissionRefusal`] when the certificate is not this program's.
pub fn interpret_http_program(
    program: &HttpProgram,
    certificate: &HttpCertificate,
) -> Result<SocketObservation, HttpEmissionRefusal> {
    let transport =
        lower_transport(program).map_err(|_| HttpEmissionRefusal::CertificateDisagrees)?;
    std_socket_c_emit::interpret_socket_program(&transport.program, &certificate.transport)
        .map_err(HttpEmissionRefusal::Transport)
}

/// Emit C11 for a checked program.
///
/// # Errors
///
/// [`HttpEmissionRefusal`] when the certificate is not this program's, or when
/// the transport backend refuses.
pub fn emit_http_c11(
    program: &HttpProgram,
    certificate: &HttpCertificate,
) -> Result<HttpCEmission, HttpEmissionRefusal> {
    let transport =
        lower_transport(program).map_err(|_| HttpEmissionRefusal::CertificateDisagrees)?;
    let (prologue, body) =
        std_socket_c_emit::entry_parts(&transport.program, &certificate.transport)
            .map_err(HttpEmissionRefusal::Transport)?;
    let http = preamble(certificate);
    let socket = std_socket_c_emit::preamble();
    let fragments = c_program::merge(&[&socket, &http]);
    Ok(HttpCEmission {
        source: c_program::assemble(
            &fragments,
            &c_program::Entry {
                prologue,
                ..c_program::Entry::source_route(body)
            },
        ),
    })
}

/// The single-emission-route check, applied to this backend (card
/// `TRACE-STDIO`).
#[must_use]
pub fn direct_stdio_calls(source: &str) -> Vec<(usize, &'static str)> {
    crate::io_emit::direct_stdio_calls(source)
}
