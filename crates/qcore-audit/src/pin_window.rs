//! The rolling window of pin lock sets (card **CONTRACT-SUPERSESSION**, user
//! decision 9a of 2026-10-26: "Option A plus a rolling window of 3 Fluent Bit
//! revisions").
//!
//! The provider tree's pin locks — every crate's `contracts.lock`,
//! `bounds-contracts.lock` and `outer-contracts.lock` — form one **lock set**,
//! tied to one Fluent Bit revision (each lock's `fluent_bit_revision`). At
//! most [`CAPACITY`] lock sets are retained: the latest, which is the **live**
//! set the audit reads from `providers/<crate>/`, and up to two before it,
//! each **archived** byte for byte under `providers/pin-lock-sets/<revision>/`
//! with its files' digests recorded. The window manifest,
//! `providers/pin-lock-window.json`, lists them oldest first.
//!
//! On each re-base of the live profiles (the `REBASE-CORPUS` cadence) a new
//! set is added and, when the window is full, the oldest is retired:
//!
//! * [`PinLockWindow::add`] archives the live set under its revision and ties
//!   the live locks to the new one; it **refuses a fourth** set;
//! * [`PinLockWindow::retire_oldest`] drops the oldest archived set (never the
//!   live one);
//! * [`PinLockWindow::rotate`] is the re-base step: retire the oldest when the
//!   window is full, then add.
//!
//! A frozen cycle outside the window keeps its report evidence (each report
//! owns its inputs) but has no live lock. Nothing here runs during an audit,
//! and no past revision is invented: today the window holds exactly one set.
//! The file operations are [`check`], [`add`], [`retire`] and [`rotate`];
//! `quirin-audit pin --window-*` runs them and `pin --verify-contracts` runs
//! [`check`] whenever the manifest exists.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use qcore_schemas::sha256_hex;
use serde::{Deserialize, Serialize};

use crate::contract_revision::ContractLock;

/// The most lock sets the window retains: the latest and the two before it.
pub const CAPACITY: usize = 3;

/// The manifest's file name, beside the load path.
pub const WINDOW_FILE: &str = "pin-lock-window.json";

/// The directory archived sets live under, beside the manifest.
pub const ARCHIVE_DIRECTORY: &str = "pin-lock-sets";

/// The lock files of one crate a set holds, in this order.
pub const LOCK_FILES: [&str; 3] = [
    "contracts.lock",
    "bounds-contracts.lock",
    "outer-contracts.lock",
];

/// The manifest's schema version.
pub const SCHEMA_VERSION: u32 = 1;

/// The manifest's note.
pub const NOTE: &str = "Generated by `quirin-audit pin --window-*`. The provider pin locks form one lock set tied to one Fluent Bit revision; at most three sets are retained (user decision 9a): the latest is live in providers/<crate>/, and up to two earlier sets are archived byte for byte under pin-lock-sets/<revision>/. A re-base adds a set and retires the oldest. Do not edit by hand.";

/// One retained lock set.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct WindowSet {
    /// The Fluent Bit revision the set is tied to (a full Git revision).
    pub fluent_bit_revision: String,
    /// `live`, or the archive directory relative to the manifest.
    pub location: String,
    /// For an archived set: every file, relative to its directory, with its
    /// SHA-256. Empty for the live set, whose locks change with every pin.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub locks: BTreeMap<String, String>,
}

/// The window manifest.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PinLockWindow {
    pub schema_version: u32,
    pub generated_by: String,
    pub note: String,
    pub capacity: usize,
    /// Oldest first; the last is the live set.
    pub sets: Vec<WindowSet>,
}

/// The location string of the live set.
pub const LIVE: &str = "live";

fn full_revision(revision: &str) -> bool {
    revision.len() == 40 && revision.bytes().all(|b| b.is_ascii_hexdigit())
}

fn archive_location(revision: &str) -> String {
    format!("{ARCHIVE_DIRECTORY}/{revision}")
}

impl PinLockWindow {
    /// A window holding only the live set, tied to `revision`.
    ///
    /// # Errors
    ///
    /// A revision that is not a full Git revision.
    pub fn new(revision: &str) -> Result<Self, String> {
        if !full_revision(revision) {
            return Err(format!("`{revision}` is not a full Git revision"));
        }
        Ok(Self {
            schema_version: SCHEMA_VERSION,
            generated_by: crate::contract_pin::GENERATED_BY.into(),
            note: NOTE.into(),
            capacity: CAPACITY,
            sets: vec![WindowSet {
                fluent_bit_revision: revision.to_owned(),
                location: LIVE.into(),
                locks: BTreeMap::new(),
            }],
        })
    }

    /// The live set's revision.
    #[must_use]
    pub fn latest(&self) -> &str {
        self.sets
            .last()
            .map_or("", |set| set.fluent_bit_revision.as_str())
    }

    /// Check the manifest's own shape: the capacity, at least one and at most
    /// [`CAPACITY`] sets, distinct full revisions, only the last live, every
    /// archived set at its own location with at least one file.
    ///
    /// # Errors
    ///
    /// The first violation.
    pub fn validate(&self) -> Result<(), String> {
        if self.schema_version != SCHEMA_VERSION {
            return Err(format!(
                "unsupported window schema_version {}",
                self.schema_version
            ));
        }
        if self.capacity != CAPACITY {
            return Err(format!(
                "the window's capacity is {}, not {CAPACITY}",
                self.capacity
            ));
        }
        if self.sets.is_empty() {
            return Err("the window holds no lock set".into());
        }
        if self.sets.len() > CAPACITY {
            return Err(format!(
                "the window holds {} lock sets; at most {CAPACITY} are retained",
                self.sets.len()
            ));
        }
        let mut seen = std::collections::BTreeSet::new();
        for (index, set) in self.sets.iter().enumerate() {
            let revision = &set.fluent_bit_revision;
            if !full_revision(revision) {
                return Err(format!("`{revision}` is not a full Git revision"));
            }
            if !seen.insert(revision) {
                return Err(format!("`{revision}` is retained twice"));
            }
            let live = index + 1 == self.sets.len();
            if live && (set.location != LIVE || !set.locks.is_empty()) {
                return Err("the latest set must be the live one, with no recorded files".into());
            }
            if !live && (set.location != archive_location(revision) || set.locks.is_empty()) {
                return Err(format!(
                    "the set of `{revision}` must be archived at {} with its files recorded",
                    archive_location(revision)
                ));
            }
        }
        Ok(())
    }

    /// Add a set tied to `revision`: the live set becomes archived with
    /// `archived` (its files and digests) and `revision` becomes live.
    /// Refuses a fourth set: retire the oldest first ([`Self::rotate`]).
    ///
    /// # Errors
    ///
    /// A full window, a revision already retained, an empty archive or a
    /// malformed revision.
    pub fn add(
        &mut self,
        revision: &str,
        archived: BTreeMap<String, String>,
    ) -> Result<(), String> {
        if !full_revision(revision) {
            return Err(format!("`{revision}` is not a full Git revision"));
        }
        if self
            .sets
            .iter()
            .any(|set| set.fluent_bit_revision == revision)
        {
            return Err(format!("`{revision}` already has a lock set in the window"));
        }
        if self.sets.len() >= CAPACITY {
            return Err(format!(
                "the window already holds {CAPACITY} lock sets; retire the oldest (`{}`) first",
                self.sets[0].fluent_bit_revision
            ));
        }
        if archived.is_empty() {
            return Err("the live set to archive has no lock file".into());
        }
        let live = self.sets.last_mut().ok_or("the window holds no lock set")?;
        live.location = archive_location(&live.fluent_bit_revision);
        live.locks = archived;
        self.sets.push(WindowSet {
            fluent_bit_revision: revision.to_owned(),
            location: LIVE.into(),
            locks: BTreeMap::new(),
        });
        Ok(())
    }

    /// Retire the oldest archived set and return it. The live set is never
    /// retired.
    ///
    /// # Errors
    ///
    /// A window holding only the live set.
    pub fn retire_oldest(&mut self) -> Result<WindowSet, String> {
        if self.sets.len() < 2 {
            return Err("the window holds only the live lock set; nothing to retire".into());
        }
        Ok(self.sets.remove(0))
    }

    /// The re-base step: retire the oldest set when the window is full, then
    /// add `revision`. Returns the retired set, if any.
    ///
    /// # Errors
    ///
    /// As [`Self::add`]; the window is unchanged on error.
    pub fn rotate(
        &mut self,
        revision: &str,
        archived: BTreeMap<String, String>,
    ) -> Result<Option<WindowSet>, String> {
        let mut next = self.clone();
        let retired = if next.sets.len() >= CAPACITY {
            Some(next.retire_oldest()?)
        } else {
            None
        };
        next.add(revision, archived)?;
        *self = next;
        Ok(retired)
    }

    /// Read and validate a manifest.
    ///
    /// # Errors
    ///
    /// An unreadable or malformed manifest.
    pub fn read(path: &Path) -> Result<Self, String> {
        let text =
            fs::read_to_string(path).map_err(|error| format!("{}: {error}", path.display()))?;
        let window: Self = serde_json::from_str(&text)
            .map_err(|error| format!("malformed pin lock window {}: {error}", path.display()))?;
        window
            .validate()
            .map_err(|error| format!("malformed pin lock window {}: {error}", path.display()))?;
        Ok(window)
    }

    /// The canonical text: two-space pretty JSON and a final newline.
    ///
    /// # Errors
    ///
    /// Serialisation failure only.
    pub fn to_text(&self) -> Result<String, String> {
        serde_json::to_string_pretty(self)
            .map(|text| text + "\n")
            .map_err(|error| error.to_string())
    }
}

/// The window manifest of a provider tree (`<dir>/pin-lock-window.json`,
/// beside its load path).
#[must_use]
pub fn manifest_path(provider_root: &Path) -> PathBuf {
    provider_root.join(WINDOW_FILE)
}

/// Every live lock of the provider tree: `<crate>/<lock file>` for every
/// direct subdirectory holding one, sorted.
///
/// # Errors
///
/// An unreadable directory.
pub fn live_locks(provider_root: &Path) -> Result<BTreeMap<String, PathBuf>, String> {
    let mut locks = BTreeMap::new();
    let entries = fs::read_dir(provider_root)
        .map_err(|error| format!("{}: {error}", provider_root.display()))?;
    for entry in entries {
        let entry = entry.map_err(|error| error.to_string())?;
        let directory = entry.path();
        if !directory.is_dir() || entry.file_name() == ARCHIVE_DIRECTORY {
            continue;
        }
        for file in LOCK_FILES {
            let path = directory.join(file);
            if path.is_file() {
                locks.insert(
                    format!("{}/{file}", entry.file_name().to_string_lossy()),
                    path,
                );
            }
        }
    }
    Ok(locks)
}

/// Verify the window against the tree: the manifest is valid, every live
/// lock is tied to the latest revision, every archived set's files exist with
/// their recorded digests and nothing else, and no other archive exists.
/// Returns one line per problem (empty when clean).
///
/// # Errors
///
/// An unreadable manifest or directory.
pub fn check(provider_root: &Path) -> Result<Vec<String>, String> {
    let window = PinLockWindow::read(&manifest_path(provider_root))?;
    let mut problems = Vec::new();
    let latest = window.latest().to_owned();
    for (name, path) in live_locks(provider_root)? {
        match ContractLock::read(&path) {
            Ok(lock) if lock.fluent_bit_revision.as_deref() == Some(latest.as_str()) => {}
            Ok(lock) => problems.push(format!(
                "{name} is tied to {}, not to the window's latest revision {latest}",
                lock.fluent_bit_revision.as_deref().unwrap_or("no revision")
            )),
            Err(error) => problems.push(error),
        }
    }
    let mut archived = std::collections::BTreeSet::new();
    for set in &window.sets[..window.sets.len() - 1] {
        archived.insert(set.fluent_bit_revision.clone());
        let directory = provider_root.join(&set.location);
        let found = archive_files(&directory)?;
        if found.keys().collect::<Vec<_>>() != set.locks.keys().collect::<Vec<_>>() {
            problems.push(format!(
                "the archived set of {} holds {:?}, not the recorded {:?}",
                set.fluent_bit_revision,
                found.keys().collect::<Vec<_>>(),
                set.locks.keys().collect::<Vec<_>>()
            ));
            continue;
        }
        for (file, digest) in &set.locks {
            if found.get(file) != Some(digest) {
                problems.push(format!(
                    "the archived {file} of {} differs from its recorded digest",
                    set.fluent_bit_revision
                ));
            }
        }
    }
    let archive_root = provider_root.join(ARCHIVE_DIRECTORY);
    if archive_root.is_dir() {
        for entry in fs::read_dir(&archive_root)
            .map_err(|error| format!("{}: {error}", archive_root.display()))?
        {
            let name = entry
                .map_err(|error| error.to_string())?
                .file_name()
                .to_string_lossy()
                .into_owned();
            if !archived.contains(&name) {
                problems.push(format!(
                    "{ARCHIVE_DIRECTORY}/{name} is no retained lock set of the window"
                ));
            }
        }
    }
    Ok(problems)
}

/// Every file under an archive directory, relative to it, with its digest.
fn archive_files(directory: &Path) -> Result<BTreeMap<String, String>, String> {
    let mut files = BTreeMap::new();
    if !directory.is_dir() {
        return Ok(files);
    }
    for crate_entry in
        fs::read_dir(directory).map_err(|error| format!("{}: {error}", directory.display()))?
    {
        let crate_entry = crate_entry.map_err(|error| error.to_string())?;
        let crate_dir = crate_entry.path();
        if !crate_dir.is_dir() {
            files.insert(
                crate_entry.file_name().to_string_lossy().into_owned(),
                String::new(),
            );
            continue;
        }
        for file in
            fs::read_dir(&crate_dir).map_err(|error| format!("{}: {error}", crate_dir.display()))?
        {
            let file = file.map_err(|error| error.to_string())?.path();
            let bytes = fs::read(&file).map_err(|error| format!("{}: {error}", file.display()))?;
            files.insert(
                format!(
                    "{}/{}",
                    crate_entry.file_name().to_string_lossy(),
                    file.file_name().unwrap_or_default().to_string_lossy()
                ),
                sha256_hex(&bytes),
            );
        }
    }
    Ok(files)
}

/// Re-tie every live lock to `revision` (its entries untouched).
fn retie(provider_root: &Path, revision: &str) -> Result<usize, String> {
    let mut count = 0;
    for path in live_locks(provider_root)?.values() {
        let mut lock = ContractLock::read(path)?;
        lock.fluent_bit_revision = Some(revision.to_owned());
        fs::write(path, lock.to_text()?).map_err(|error| format!("{}: {error}", path.display()))?;
        count += 1;
    }
    Ok(count)
}

/// Create the window with the live set tied to `revision`, which every live
/// lock must already name (the one-time re-pin ties them).
///
/// # Errors
///
/// An existing manifest, or a live lock tied elsewhere.
pub fn create(provider_root: &Path, revision: &str) -> Result<PinLockWindow, String> {
    let path = manifest_path(provider_root);
    if path.exists() {
        return Err(format!("{} already exists", path.display()));
    }
    let window = PinLockWindow::new(revision)?;
    for (name, lock) in live_locks(provider_root)? {
        let tie = ContractLock::read(&lock)?.fluent_bit_revision;
        if tie.as_deref() != Some(revision) {
            return Err(format!(
                "{name} is tied to {}, not to {revision}",
                tie.as_deref().unwrap_or("no revision")
            ));
        }
    }
    fs::write(&path, window.to_text()?).map_err(|error| format!("{}: {error}", path.display()))?;
    Ok(window)
}

/// Archive the live set under its revision and tie the live locks to
/// `revision`, retiring the oldest set first when `rotate` is set and the
/// window is full. Returns the window and the retired set.
///
/// # Errors
///
/// As [`PinLockWindow::add`] (a fourth set without `rotate`); nothing is
/// written then.
pub fn add(
    provider_root: &Path,
    revision: &str,
    rotate: bool,
) -> Result<(PinLockWindow, Option<WindowSet>), String> {
    let path = manifest_path(provider_root);
    let mut window = PinLockWindow::read(&path)?;
    let problems = check(provider_root)?;
    if !problems.is_empty() {
        return Err(format!(
            "the window does not check: {}",
            problems.join("; ")
        ));
    }
    let previous = window.latest().to_owned();
    let live = live_locks(provider_root)?;
    let mut archived = BTreeMap::new();
    let mut copies = Vec::new();
    for (name, source) in &live {
        let bytes = fs::read(source).map_err(|error| format!("{}: {error}", source.display()))?;
        archived.insert(name.clone(), sha256_hex(&bytes));
        copies.push((name.clone(), bytes));
    }
    let retired = if rotate {
        window.rotate(revision, archived)?
    } else {
        window.add(revision, archived)?;
        None
    };
    let directory = provider_root.join(archive_location(&previous));
    for (name, bytes) in copies {
        let target = directory.join(&name);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent).map_err(|error| format!("{}: {error}", parent.display()))?;
        }
        fs::write(&target, bytes).map_err(|error| format!("{}: {error}", target.display()))?;
    }
    if let Some(set) = &retired {
        remove_archive(provider_root, set)?;
    }
    retie(provider_root, revision)?;
    fs::write(&path, window.to_text()?).map_err(|error| format!("{}: {error}", path.display()))?;
    Ok((window, retired))
}

/// Retire the oldest archived set: drop it from the manifest and delete its
/// directory (frozen reports keep their own evidence).
///
/// # Errors
///
/// A window holding only the live set.
pub fn retire(provider_root: &Path) -> Result<WindowSet, String> {
    let path = manifest_path(provider_root);
    let mut window = PinLockWindow::read(&path)?;
    let retired = window.retire_oldest()?;
    remove_archive(provider_root, &retired)?;
    fs::write(&path, window.to_text()?).map_err(|error| format!("{}: {error}", path.display()))?;
    Ok(retired)
}

fn remove_archive(provider_root: &Path, set: &WindowSet) -> Result<(), String> {
    if set.location == LIVE || !set.location.starts_with(ARCHIVE_DIRECTORY) {
        return Err(format!("refusing to remove {}", set.location));
    }
    let directory = provider_root.join(&set.location);
    if directory.is_dir() {
        fs::remove_dir_all(&directory)
            .map_err(|error| format!("{}: {error}", directory.display()))?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn revision(n: u8) -> String {
        format!("{n:x}").repeat(40)
    }

    fn files(tag: &str) -> BTreeMap<String, String> {
        BTreeMap::from([("crate/contracts.lock".to_owned(), tag.repeat(64))])
    }

    #[test]
    fn the_window_adds_retires_and_refuses_a_fourth() {
        let mut window = PinLockWindow::new(&revision(1)).unwrap();
        window.validate().unwrap();
        assert!(
            window.retire_oldest().is_err(),
            "the live set is never retired"
        );
        window.add(&revision(2), files("a")).unwrap();
        window.add(&revision(3), files("b")).unwrap();
        window.validate().unwrap();
        assert_eq!(window.sets.len(), CAPACITY);
        assert_eq!(window.latest(), revision(3));
        let full = window.clone();
        let error = window.add(&revision(4), files("c")).unwrap_err();
        assert!(error.contains("retire the oldest"), "{error}");
        assert_eq!(window, full, "a refused add changes nothing");
        assert!(
            window.add(&revision(2), files("c")).is_err(),
            "no revision twice"
        );
        let retired = window.rotate(&revision(4), files("c")).unwrap().unwrap();
        assert_eq!(retired.fluent_bit_revision, revision(1));
        window.validate().unwrap();
        assert_eq!(
            window
                .sets
                .iter()
                .map(|set| set.fluent_bit_revision.clone())
                .collect::<Vec<_>>(),
            vec![revision(2), revision(3), revision(4)]
        );
        let retired = window.retire_oldest().unwrap();
        assert_eq!(retired.fluent_bit_revision, revision(2));
        window.validate().unwrap();
        // Rotating a window with room retires nothing.
        assert_eq!(window.rotate(&revision(5), files("d")).unwrap(), None);
        assert_eq!(window.sets.len(), CAPACITY);
    }

    #[test]
    fn a_malformed_window_refuses() {
        let mut window = PinLockWindow::new(&revision(1)).unwrap();
        assert!(PinLockWindow::new("046accf6").is_err());
        window.sets.push(window.sets[0].clone());
        assert!(window.validate().is_err(), "two live sets");
        let mut window = PinLockWindow::new(&revision(1)).unwrap();
        for n in 2..=4 {
            window.sets.insert(
                0,
                WindowSet {
                    fluent_bit_revision: revision(n),
                    location: archive_location(&revision(n)),
                    locks: files("e"),
                },
            );
        }
        assert!(window.validate().unwrap_err().contains("at most 3"));
    }
}
