"""Generate the unpublished-landings sentence of `docs/STATUS.md` from the
landing gate records and the publication records (card
STATUS-REGROWTH-BY-PREPEND). `scripts/land.py` owns the commands:
`land.py unpublished` prints the landings, `land.py unpublished --write`
rewrites the sentence, and `land.py check` fails while it is stale. Nobody
edits the sentence by hand.

Inputs, all read from the working tree, listed through git (`git ls-files
--cached --others --exclude-standard`, so ignored content such as `private/`
never counts, and a gate record written but not yet staged does):

- Landing gate records: `docs/reports/<dir>/integration/gate.json` (or
  archived `docs/reports/archive/<category>/<dir>/integration/gate.json`) whose
  `note` begins `Landing integrate/<label>`. The label is `rN` for the
  numbered landings and a branch word otherwise (`integrate/ag-gaps`).
  Records with an identical label and note are one landing (integrate/r8 left
  one copy per merged card). The cards are the `NAME <revision>` pairs of the
  note's `merges ...` clause; a record without one falls back to its report
  directory, upper-cased, and is listed as a problem.
- Publication records, from two places. (1) Each evaluation profile's
  `baseline_history` entry whose `reason` begins `Landing <revision>`: a
  publication that moved a committed baseline (the only kind before this
  card). (2) `docs/development/landing-publications.json`, to which `land.py
  publish` appends every publication, so a publication that moved no
  baseline is recorded too.

A landing is published when one of its gate records is in the tree of a
published revision (`git cat-file -e REV:path`): a landing commits its gate
record, so every later landing's record is absent from an earlier
publication. Everything else is unpublished. A published revision missing
from the object store is an error, never "unpublished" or "published" by
default. The newest publication is the published revision with the latest
committer time.
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

STATUS = Path("docs/STATUS.md")
PUBLICATIONS = Path("docs/development/landing-publications.json")
PUBLICATIONS_SCHEMA = "quirin-landing-publications/1"
EVALUATIONS = Path("contract/evaluations")
START = "<!-- unpublished-landings:"
END = "<!-- unpublished-landings:end -->"
START_LINE = ("<!-- unpublished-landings: generated by `python3 scripts/land.py unpublished "
              "--write` from the landing gate records and the publication records; never "
              "edit by hand. -->")
WRITE_COMMAND = "python3 scripts/land.py unpublished --write"
LANDING_RE = re.compile(r"Landing integrate/([A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)")
NUMBERED_RE = re.compile(r"r(\d+)")
MERGES_RE = re.compile(r"\bmerges(?:, in order,)? ")
CARD_RE = re.compile(r"(?<![A-Za-z0-9/-])([A-Z0-9]+(?:-[A-Z0-9]+)+(?: (?:round|phase) \d+| D\d+)?)"
                     r" [0-9a-f]{7,40}\b")
HISTORY_RE = re.compile(r"Landing ([0-9a-f]{7,40})\b")
DECISION = (
    "The landing host holds no prepared live-route inputs (`--inputs-base` absent, no "
    "`build/cycle19`) and no `private/baselines/`, and a fresh preparation here would not "
    "reproduce the committed baselines, so `land.py publish` is deferred rather than forced. "
    "Their figures are landing-gate counts, not published baselines; publish from the host "
    "that holds the prepared inputs (`land.py publish --previous {previous}`).")


class LandingError(Exception):
    """The records cannot be read; the sentence is not generated."""


class Git:
    """The git queries the generator makes, in `root`."""

    def __init__(self, root, untracked=True):
        self.root = Path(root)
        # A gate record written at landing step 1 counts before it is staged;
        # ignored content (`private/`) never does. Tests pass untracked=False
        # (constraint 29: the index is the source).
        self.untracked = untracked

    def _run(self, *args):
        return subprocess.run(["git", "-C", str(self.root), *args],
                              capture_output=True, text=True)

    def listed(self, pathspec):
        others = ("--others", "--exclude-standard") if self.untracked else ()
        result = self._run("ls-files", "--cached", *others, "-z", "--", pathspec)
        if result.returncode != 0:
            raise LandingError(f"git ls-files failed in {self.root}: {result.stderr.strip()}")
        paths = {path for path in result.stdout.split("\0") if path}
        if self.untracked:
            paths = {path for path in paths if (self.root / path).is_file()}
        return sorted(paths)

    def contains(self, revision, path):
        if self._run("cat-file", "-e", f"{revision}^{{commit}}").returncode != 0:
            raise LandingError(f"published revision {revision} is not in this checkout's "
                               "object store (a shallow clone?)")
        return self._run("cat-file", "-e", f"{revision}:{path}").returncode == 0

    def time(self, revision):
        result = self._run("show", "-s", "--format=%ct", f"{revision}^{{commit}}")
        if result.returncode != 0:
            raise LandingError(f"published revision {revision} is not in this checkout's "
                               "object store")
        return int(result.stdout.strip())


def cards_of(note):
    """The card names of a landing note's `merges ...` clause, in order."""
    found = MERGES_RE.search(note)
    if not found:
        return []
    rest, depth, clause = note[found.end():], 0, []
    for index, character in enumerate(rest):
        if character == "(":
            depth += 1
        elif character == ")":
            if depth == 0:
                break
            depth -= 1
        elif depth == 0:
            if character == ";" or (character == "." and rest[index + 1:index + 2] in ("", " ")):
                break
            clause.append(character)
    return CARD_RE.findall("".join(clause))


def _card_dir_of_gate_record(path):
    parts = Path(path).parts
    if (len(parts) == 5 and parts[:2] == ("docs", "reports") and parts[2] != "archive"
            and parts[3:] == ("integration", "gate.json")):
        return parts[2]
    if (len(parts) == 7 and parts[:3] == ("docs", "reports", "archive")
            and parts[5:] == ("integration", "gate.json")):
        return parts[4]
    return None


def _published_contains(git, revision, path):
    if git.contains(revision, path):
        return True
    parts = Path(path).parts
    if (len(parts) == 7 and parts[:3] == ("docs", "reports", "archive")
            and parts[5:] == ("integration", "gate.json")):
        return git.contains(revision, f"docs/reports/{parts[4]}/integration/gate.json")
    return False


def read_landings(root, git):
    """Every landing as a dict (label, number, cards, records, fallback), in
    landing order, and the problems found."""
    groups, problems = {}, []
    candidates = sorted(
        set(git.listed("docs/reports/*/integration/gate.json"))
        | set(git.listed("docs/reports/archive/*/*/integration/gate.json"))
    )
    for path in candidates:
        if _card_dir_of_gate_record(path) is None:
            continue
        try:
            record = json.loads((Path(root) / path).read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            raise LandingError(f"{path}: cannot read JSON ({error})") from error
        note = record.get("note") if isinstance(record, dict) else None
        if not isinstance(note, str):
            continue
        match = LANDING_RE.match(note)
        if not match:
            continue
        label = match.group(1)
        group = groups.setdefault((label, note), {
            "label": label, "records": [], "cards": cards_of(note), "fallback": False})
        group["records"].append(path)
    landings = []
    for (label, _), group in groups.items():
        numbered = NUMBERED_RE.fullmatch(label)
        group["number"] = int(numbered.group(1)) if numbered else None
        if group["number"] is None:
            problems.append(f"{group['records'][0]}: integrate/{label} has no rN number")
        if not group["cards"]:
            directory = _card_dir_of_gate_record(group["records"][0]) or Path(group["records"][0]).parts[2]
            group["cards"] = [directory.upper()]
            group["fallback"] = True
            problems.append(f"{group['records'][0]}: integrate/{label}'s note has no "
                            f"'merges CARD <revision>' clause; named by its directory "
                            f"{directory.upper()}")
        landings.append(group)
    landings.sort(key=lambda g: (g["number"] is None, g["number"] or 0, g["label"],
                                 _card_dir_of_gate_record(g["records"][0]) or g["records"][0]))
    return landings, problems


def read_publications(root):
    """{revision: {"profiles": [...], "sources": [...]}} from both publication
    records (module doc)."""
    root = Path(root)
    found = {}
    evaluations = root / EVALUATIONS
    if evaluations.is_dir():
        for directory in sorted(evaluations.iterdir()):
            path = directory / "evaluation.json"
            if not path.is_file():
                continue
            try:
                record = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError) as error:
                raise LandingError(f"{path.relative_to(root)}: cannot read JSON ({error})") from error
            for entry in record.get("baseline_history") or []:
                reason = entry.get("reason") if isinstance(entry, dict) else None
                revision = entry.get("measured_revision") if isinstance(entry, dict) else None
                if not isinstance(reason, str) or not HISTORY_RE.match(reason):
                    continue
                if not isinstance(revision, str) or not revision.startswith(
                        HISTORY_RE.match(reason).group(1)):
                    raise LandingError(f"{path.relative_to(root)}: a 'Landing' history entry's "
                                       "measured_revision does not match its reason")
                slot = found.setdefault(revision, {"profiles": [], "sources": []})
                slot["profiles"].append(record.get("name", directory.name))
                if isinstance(entry.get("source"), str) and entry["source"] not in slot["sources"]:
                    slot["sources"].append(entry["source"])
    ledger = root / PUBLICATIONS
    if ledger.is_file():
        try:
            document = json.loads(ledger.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            raise LandingError(f"{PUBLICATIONS}: cannot read JSON ({error})") from error
        if (not isinstance(document, dict) or document.get("schema") != PUBLICATIONS_SCHEMA
                or not isinstance(document.get("publications"), list)):
            raise LandingError(f"{PUBLICATIONS} is not a {PUBLICATIONS_SCHEMA} record")
        for entry in document["publications"]:
            revision = entry.get("revision") if isinstance(entry, dict) else None
            if not isinstance(revision, str) or not re.fullmatch(r"[0-9a-f]{40}", revision):
                raise LandingError(f"{PUBLICATIONS}: an entry without a full revision")
            found.setdefault(revision, {"profiles": [], "sources": []})
            pub_source = PUBLICATIONS.as_posix()
            if pub_source not in found[revision]["sources"]:
                found[revision]["sources"].append(pub_source)
    return found


def _join(items, conjunction="and"):
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + f" {conjunction} " + items[-1]


def _named(landing, prefix=""):
    return f"{prefix}{landing['label']} ({_join(landing['cards'])})"


def _link(source):
    return source[len("docs/"):] if source.startswith("docs/") else f"../{source}"


def state(root, git=None):
    """(landings, unpublished landings, newest publication or None, problems)."""
    git = git or Git(root)
    landings, problems = read_landings(root, git)
    publications = read_publications(root)
    newest = None
    if publications:
        revision = max(publications, key=lambda rev: (git.time(rev), rev))
        newest = dict(publications[revision], revision=revision)
    unpublished = [landing for landing in landings
                   if not any(_published_contains(git, revision, path) for revision in publications
                              for path in landing["records"])]
    return landings, unpublished, newest, problems


def render_sentence(unpublished, newest):
    """The one-line sentence between the markers."""
    if newest is None:
        head = ("Unpublished landings (user decision 2026-11-16): no committed record of a "
                "published landing exists")
        previous = "<previous landing>"
    else:
        short = newest["revision"][:9]
        what = []
        if newest["profiles"]:
            what.append(_join(sorted(set(newest["profiles"]))))
        else:
            what.append("no baseline moved")
        what += [f"[record]({_link(source)})" for source in newest["sources"]]
        head = (f"Unpublished landings (user decision 2026-11-16): the newest committed landing "
                f"baseline record is `{short}` ({', '.join(what)})")
        previous = short
    if not unpublished and newest is None:
        return ("Unpublished landings: none; no landing gate record "
                "(`docs/reports/*/integration/gate.json`) exists.")
    if not unpublished:
        return (head + "; every landing gate record (`docs/reports/*/integration/gate.json`) "
                "is in a published landing, so no landing is unpublished.")
    numbered = [landing for landing in unpublished if landing["number"] is not None]
    named = [landing for landing in unpublished if landing["number"] is None]
    count = len(unpublished)
    spans, gaps = [], []
    if numbered:
        first, last = numbered[0], numbered[-1]
        span = _named(first, "integrate/")
        if last is not first:
            span += " to " + _named(last)
        present = {landing["number"] for landing in numbered}
        gaps = [f"r{n}" for n in range(first["number"], last["number"] + 1) if n not in present]
        spans.append(span)
    spans += [_named(landing, "integrate/") for landing in named]
    subject = "1 landing" if count == 1 else f"{count} landings"
    return (f"{head}; no later landing has one, so {subject} completed steps 1–7 of "
            "`scripts/land.py` (records, full landing gate, merge) but not step 8: "
            f"{_join(spans)}"
            + (f"; {_join(gaps)} {'has' if len(gaps) == 1 else 'have'} no unpublished landing "
               "gate record" if gaps else "")
            + ". `python3 scripts/land.py unpublished` lists each with its cards, "
            "read from the landing gate records (`docs/reports/*/integration/gate.json`). "
            + DECISION.format(previous=previous))


def block_bounds(text):
    """(start, end) character offsets of the generated block's lines: from the
    start marker line through the end marker line."""
    starts = [m.start() for m in re.finditer(r"^" + re.escape(START) + r"(?!end -->)", text, re.M)]
    ends = [m.start() for m in re.finditer(r"^" + re.escape(END) + r"$", text, re.M)]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise LandingError(f"{STATUS} must hold exactly one '{START} ... -->' line followed by "
                           f"one '{END}' line ({len(starts)} start, {len(ends)} end)")
    return starts[0], ends[0] + len(END)


def regenerate(text, sentence):
    start, end = block_bounds(text)
    return text[:start] + f"{START_LINE}\n{sentence}\n{END}" + text[end:]


def generated_status(root, git=None):
    """(current STATUS text, regenerated STATUS text, problems)."""
    root = Path(root)
    path = root / STATUS
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        raise LandingError(f"{STATUS} cannot be read ({error})") from error
    _, unpublished, newest, problems = state(root, git)
    return text, regenerate(text, render_sentence(unpublished, newest)), problems


def listing(root, git=None):
    """Lines describing every landing, for `land.py unpublished`."""
    landings, unpublished, newest, problems = state(root, git)
    waiting = {id(landing) for landing in unpublished}
    lines = [f"newest publication: {newest['revision'] if newest else 'none'}"]
    for landing in landings:
        mark = "unpublished" if id(landing) in waiting else "published"
        lines.append(f"integrate/{landing['label']}: {mark}: {_join(landing['cards'])} "
                     f"[{', '.join(landing['records'])}]")
    lines.append(f"{len(unpublished)} of {len(landings)} landings unpublished")
    lines += [f"problem: {problem}" for problem in problems]
    return lines
