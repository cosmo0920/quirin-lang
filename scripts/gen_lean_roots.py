"""Generate the Lean roots `proof/QCore.lean` and `proof/AuditAll.lean`.

A card adds `proof/QCore/<Module>.lean` (and its own `proof/Audit<Module>.lean`)
and reruns this script; it never edits a root by hand. `QCore.lean` imports
every module under `proof/QCore/` in sorted order. Lean 4 builds each imported
module independently from its own `import` lines, so the order of a root's
import list decides no build order and no declaration; the generated root
was checked to elaborate the identical audited declaration set as the
hand-ordered root it replaced (docs/reports/generated-roots/README.md).
`AuditAll.lean` imports the root only, so its text is fixed here.

Regenerate with `python3 scripts/gen_lean_roots.py`; validate with `--check`.
On a merge conflict in either root, take either side and rerun the script.
"""
